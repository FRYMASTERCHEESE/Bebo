// Synthetic/read-only Bebo Skin Studio safety and feature checks.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../skin-studio.js',import.meta.url),'utf8');
const {skinDesign,importSkinJSON,exportSkinJSON,studioPanels}=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(source));
const design={name:'My Dream Skin ♥',primary_color:'#c52d61',secondary_color:'#f5b2ce',accent_color:'#ffffff',layout:'right',motion:'soft'};
assert.deepEqual(skinDesign(design),design,'All validated design controls survive round-trip');
const json=exportSkinJSON({...design,background_path:'private/something.png',banner_path:'private/banner.png',creator_id:'sensitive'});
assert(!json.includes('private/')&&!json.includes('creator_id'),'Export must not expose account IDs, image paths or private files');
assert.deepEqual(importSkinJSON(json),design,'Exported design must re-import without loss');
assert.throws(()=>importSkinJSON('not json'),/valid skin JSON/,'Invalid JSON fails safely');
assert.throws(()=>importSkinJSON(JSON.stringify({...design,format:'other',version:1})),/Bebo Skin Studio/);
assert.throws(()=>skinDesign({...design,primary_color:'url(javascript:evil)'}),/valid colours/,'Untrusted CSS blocked');
assert.throws(()=>skinDesign({...design,layout:'hacker'}),/supported layout/,'Unknown layout rejected');
assert.throws(()=>skinDesign({...design,motion:'script'}),/supported layout/,'Unknown animation rejected');
const esc=x=>String(x??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const panel=(title,html)=>'<section><h2>'+esc(title)+'</h2>'+html+'</section>';
const mine=[{...design,id:'11111111-1111-4111-8111-111111111111',name:'<img src=x onerror=alert(1)>',is_hidden:false,is_draft:true,banner_path:'',background_path:''}];
const html=studioPanels(mine,mine[0].id,esc,panel,()=>null);
assert(html.includes('Private draft'),'Private own draft management exists');
assert(html.includes('data-action="skin-edit"'),'Edit control exists');
assert(html.includes('data-action="skin-export"'),'Export control exists');
assert(html.includes('data-action="skin-delete"'),'Delete control exists');
assert(html.includes('data-studio-drop="right"'),'Drag-and-drop target exists');
assert(html.includes('name="background"'),'Page background upload exists');
assert(html.includes('name="accent"'),'Accent selector exists');
assert(html.includes('name="motion"'),'Gentle animation selector exists');
assert(html.includes('name="visibility"'),'Draft/publish selector exists');
assert(!html.includes('<img src=x onerror'),'Creator-supplied markup is escaped');
const main=readFileSync(new URL('../social.js',import.meta.url),'utf8');
assert(main.includes("if(row.is_hidden)throw Error"),'Moderated skins cannot be applied');
assert(main.includes("row.is_draft&&row.creator_id!==me.id"),'Other members cannot apply drafts');
assert(main.includes('skin_background_path:backgroundPath'),'Published design copies background to profile');
assert(main.includes("await query('bebo_skins',q=>q.delete()"),'Delete goes through owner-scoped server RLS');
assert(main.includes("await query('bebo_skins',q=>q.update(values)"),'Edit goes through owner-scoped server RLS');
console.log('PASS Skin Studio: safe colours, import/export, private drafts, edit/delete, background, animation, layout, and escaped HTML');
